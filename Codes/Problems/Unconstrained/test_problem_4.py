# ============================================================

def _test_problem_4(x):

    x = np.atleast_2d(np.asarray(x, dtype=float))

    nvar = x.shape[1]

    x1 = x[:, 0]
    x2 = x[:, 1]
    xi = x[:, 2:]

    # --------------------------------------------------------
    # h(x1,x2)
    # --------------------------------------------------------
    z = x1 + x2

    h = (
        2.0
        - x1
        - 0.8 * np.exp(-((z - 0.35) / 0.25) ** 2)
        - np.exp(-((z - 0.85) / 0.03) ** 2)
    )

    # --------------------------------------------------------
    # g(x)
    # --------------------------------------------------------
    g = np.sum(
        50.0 * xi**2,
        axis=1
    )

    # --------------------------------------------------------
    # S(x1)
    # --------------------------------------------------------
    S = 1.0 - np.sqrt(x1)

    # --------------------------------------------------------
    # objectives
    # --------------------------------------------------------
    f1 = x1
    f2 = h * (g + S)

    F = np.column_stack([f1, f2])

    G = np.zeros((x.shape[0], 0))

    return F, G


